object AppStrings {

    fun forLanguage(lang: AppLanguage): LocalizedStrings = when (lang) {
        AppLanguage.ENGLISH -> english
        AppLanguage.BENGALI -> bengali
        AppLanguage.ARABIC -> arabic
    }

    fun localizeDigits(input: String, lang: AppLanguage): String {
        return when (lang) {
            AppLanguage.ENGLISH -> input
            AppLanguage.BENGALI -> input.map { ch ->
                if (ch in '0'..'9') ('০'.code + (ch - '0')).toChar() else ch
            }.joinToString("")
            AppLanguage.ARABIC -> input.map { ch ->
                if (ch in '0'..'9') ('٠'.code + (ch - '0')).toChar() else ch
            }.joinToString("")
        }
    }

